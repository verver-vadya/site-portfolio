// Настройки движения кольца. Обычно это просто числа ниже; с ?dial в адресе их можно
// крутить вживую в панели DialKit (components/DialTune.tsx), сцена читает их каждый кадр.
export const TUNE_DEFAULTS = {
  enterTime: 2.9, // секунд: кольцо поднимается из воды
  leaveTime: 0.7, // секунд: уходит под воду, когда листают назад к надписи
  hover: 0.12, // насколько выдвигается экран под курсором
  autoStep: 5, // секунд между шагами, когда кольцо крутится само
  dragSpeed: 1.05, // сколько кольцо проходит за движением пальца или мыши
  inertia: 3.2, // как быстро гаснет бросок: больше — короче
  spring: 26, // жёсткость доводки до ближайшего экрана: больше — резче
};

export type Tune = typeof TUNE_DEFAULTS;
export const tune: Tune = { ...TUNE_DEFAULTS };
